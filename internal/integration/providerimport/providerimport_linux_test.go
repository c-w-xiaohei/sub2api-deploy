func readPort(t *testing.T, reader io.Reader) string {
	t.Helper()
	result := make(chan struct {
		line string
		err  error
	}, 1)
	go func() {
		line, err := bufio.NewReader(reader).ReadString('\n')
		result <- struct {
			line string
			err  error
		}{line, err}
	}()
	select {
	case value := <-result:
		if value.err != nil {
			t.Fatal(value.err)
		}
		port := strings.TrimSpace(value.line)
		if _, err := strconv.Atoi(port); err != nil {
			t.Fatalf("invalid provider port %q", port)
		}
		return port
	case <-time.After(5 * time.Second):
		t.Fatal("provider did not emit a port within 5 seconds")
		return ""
	}
}
func processStart(pid int) string {
	b, err := os.ReadFile(fmt.Sprintf("/proc/%d/stat", pid))
	if err != nil {
		return ""
	}
	close := strings.LastIndexByte(string(b), ')')
	fields := strings.Fields(string(b)[close+1:])
	if len(fields) < 20 {
		return ""
	}
	return fields[19]
}
func stopProvider(t *testing.T, p *providerProcess) {
	t.Helper()
	p.stopOnce.Do(func() {
		defer close(p.stopped)
		if p.proxy != nil {
			p.proxy.Stop()
		}
		if p.proxyListener != nil {
			_ = p.proxyListener.Close()
		}
		if p.identity.start != "" && processStart(p.identity.pid) == p.identity.start {
			_ = syscall.Kill(-p.identity.pid, syscall.SIGTERM)
		}
		select {
		case <-p.done:
			return
		case <-time.After(time.Second):
		}
		if p.identity.start != "" && processStart(p.identity.pid) == p.identity.start {
			_ = syscall.Kill(-p.identity.pid, syscall.SIGKILL)
		}
		select {
		case <-p.done:
		case <-time.After(time.Second):
			t.Errorf("provider process did not exit")
		}
	})
	<-p.stopped
}
