func secretOnlyProperty(values resource.PropertyMap, canary string, secret bool) bool {
	for _, value := range values {
		if !secretOnlyValue(value, canary, secret) {
			return false
		}
	}
	return true
}
func secretOnlyValue(value resource.PropertyValue, canary string, secret bool) bool {
	if value.IsSecret() {
		return secretOnlyValue(value.SecretValue().Element, canary, true)
	}
	if value.IsString() {
		return !strings.Contains(value.StringValue(), canary) || secret
	}
	if value.IsArray() {
		for _, child := range value.ArrayValue() {
			if !secretOnlyValue(child, canary, secret) {
				return false
			}
		}
	}
	if value.IsObject() {
		for _, child := range value.ObjectValue() {
			if !secretOnlyValue(child, canary, secret) {
				return false
			}
		}
	}
	return true
}
func assertCanonicalHostInputs(t *testing.T, imported, programInputs resource.PropertyMap) {
	t.Helper()
	if len(imported) != 4 || len(programInputs) != 4 {
		t.Fatal("Host inputs do not have the complete expected top-level shape")
	}
	for _, key := range []resource.PropertyKey{"resource", "server", "target", "secrets"} {
		importedValue, importedOK := imported[key]
		programValue, programOK := programInputs[key]
		if !importedOK || !programOK || importedValue.ContainsSecrets() != programValue.ContainsSecrets() {
			t.Fatalf("import checkpoint %s differs in presence or secret classification", key)
		}
	}
	for _, key := range []resource.PropertyKey{"resource", "server"} {
		if !reflect.DeepEqual(imported[key], programInputs[key]) {
			t.Fatalf("import checkpoint %s differs from the registered Host input", key)
		}
	}
	var importedTarget, programTarget hostcontract.Target
	var importedSecrets, programSecrets hostcontract.Secrets
	if !decodePropertyJSON(imported["target"], &importedTarget) || !decodePropertyJSON(programInputs["target"], &programTarget) || !decodePropertyJSON(imported["secrets"], &importedSecrets) || !decodePropertyJSON(programInputs["secrets"], &programSecrets) {
		t.Fatal("decode canonical Host inputs")
	}
	importedTarget, importedSecrets = hostcontract.NormalizeTargetSecrets(importedTarget, importedSecrets)
	programTarget, programSecrets = hostcontract.NormalizeTargetSecrets(programTarget, programSecrets)
	if !reflect.DeepEqual(importedTarget, programTarget) || !reflect.DeepEqual(importedSecrets, programSecrets) {
		t.Fatal("import checkpoint Host inputs differ from program inputs")
	}
}
